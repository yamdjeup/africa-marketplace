import { getLang, tr, lazy } from "./region";
import { useEffect, useMemo, useRef, useState } from "react";
import AsyncStorage from "@react-native-async-storage/async-storage";
import { useSafeAreaInsets } from "react-native-safe-area-context";
import { ActivityIndicator, Animated, BackHandler, Image, KeyboardAvoidingView, PanResponder, Platform, Pressable, ScrollView, StyleSheet, Text, TextInput, View } from "react-native";
import { authed } from "./api";
import { API_URL } from "./config";

// Reprend src/components/tila/tila-chat.tsx (textes FR, 10 derniers messages, 500 caractères, fiches produit) via POST /api/tila.
type Card = { slug: string; name: string; creatorName: string; priceCents: number; image: string | null };
type Msg = { role: "user" | "assistant"; content: string; products?: Card[] };

const T = lazy(() => ({
  name: "Tílá",
  badge: tr("Assistant IA", "AI assistant"),
  open: tr("Ouvrir Tílá, l'assistant IA d'achat", "Open Tílá, the AI shopping assistant"),
  hello: tr("Bonjour, je suis Tílá, votre assistant IA. Dites-moi ce que vous cherchez (occasion, tissu, budget) et je vous montre des pièces en stock.", "Hello, I'm Tílá, your AI assistant. Tell me what you're looking for (occasion, fabric, budget) and I'll show you pieces in stock."),
  placeholder: tr("Votre message…", "Your message…"),
  send: tr("Envoyer", "Send"),
  notice: tr("Réponses générées par une IA, qui peut se tromper. Ne saisissez pas de données personnelles.", "Answers are generated by an AI, which can be wrong. Do not enter personal data."),
  thinking: tr("Tílá réfléchit…", "Tílá is thinking…"),
  errors: { rate: tr("Vous avez posé beaucoup de questions : réessayez dans un moment.", "You have asked a lot of questions: please try again in a moment."), unavailable: tr("Tílá est momentanément indisponible. Réessayez plus tard.", "Tílá is temporarily unavailable. Please try again later."), invalid: tr("Message trop long ou invalide.", "Message too long or invalid.") } as Record<string, string>,
}));
const eur = (c: number) => `${(c / 100).toFixed(2).replace(".", ",")} €`;
const abs = (u: string) => (u.startsWith("/") ? `${API_URL}${u}` : u);
const AVATAR = `${API_URL}/tila-avatar.jpeg`;

export function TilaButton({ onOpenSlug }: { onOpenSlug: (slug: string) => void }) {
  const insets = useSafeAreaInsets();
  const [box, setBox] = useState({ w: 0, h: 0 });
  const W = box.w, H = box.h;
  const [size, setSize] = useState({ w: 150, h: 52 });
  const pos = useRef(new Animated.ValueXY({ x: -1, y: -1 })).current;
  const cur = useRef({ x: -1, y: -1 });
  const start = useRef({ x: 0, y: 0 });
  const bounds = useRef({ minY: 0, maxY: 0, maxX: 0 });
  bounds.current = { minY: 60, maxY: Math.max(60, H - 64 - Math.max(insets.bottom, Platform.OS === "android" ? 16 : 0) - size.h), maxX: Math.max(0, W - size.w - 12) };
  const clampY = (y: number) => Math.min(Math.max(y, bounds.current.minY), bounds.current.maxY);
  const place = (x: number, y: number) => { cur.current = { x, y }; pos.setValue({ x, y }); };
  useEffect(() => {
    if (!W || !H) return;
    AsyncStorage.getItem("tila.pos").then((v) => {
      try { const p = v ? JSON.parse(v) : null; if (p && typeof p.y === "number") return place(p.side === "left" ? 12 : bounds.current.maxX, clampY(p.y)); } catch {}
      place(bounds.current.maxX, bounds.current.maxY);
    }).catch(() => place(bounds.current.maxX, bounds.current.maxY));
  }, [W > 0 && H > 0]);
  useEffect(() => { if (W && H && cur.current.x >= 0) place(cur.current.x > W / 2 - size.w / 2 ? bounds.current.maxX : 12, clampY(cur.current.y)); }, [W, H, size.w, size.h]);
  const pan = useMemo(() => PanResponder.create({
    onStartShouldSetPanResponder: () => true,
    onMoveShouldSetPanResponder: (_e, g) => Math.abs(g.dx) > 8 || Math.abs(g.dy) > 8,
    onPanResponderGrant: () => { start.current = { ...cur.current }; },
    onPanResponderMove: (_e, g) => { if (Math.abs(g.dx) > 8 || Math.abs(g.dy) > 8) pos.setValue({ x: Math.min(Math.max(start.current.x + g.dx, 12), bounds.current.maxX), y: clampY(start.current.y + g.dy) }); },
    onPanResponderRelease: (_e, g) => {
      if (Math.abs(g.dx) <= 8 && Math.abs(g.dy) <= 8) return setOpen(true);
      const nx = Math.min(Math.max(start.current.x + g.dx, 12), bounds.current.maxX);
      const side = nx + size.w / 2 < W / 2 ? "left" : "right";
      const x = side === "left" ? 12 : bounds.current.maxX;
      const y = clampY(start.current.y + g.dy);
      cur.current = { x, y };
      Animated.spring(pos, { toValue: { x, y }, useNativeDriver: false, bounciness: 4 }).start();
      AsyncStorage.setItem("tila.pos", JSON.stringify({ side, y })).catch(() => {});
    },
  }), [W, H, size.w, size.h, insets.top, insets.bottom]);
  const [open, setOpen] = useState(false);
  const [msgs, setMsgs] = useState<Msg[]>([]);
  const [text, setText] = useState("");
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState("");
  const scroller = useRef<ScrollView>(null);
  useEffect(() => {
    if (!open) return;
    const sub = BackHandler.addEventListener("hardwareBackPress", () => { setOpen(false); return true; });
    return () => sub.remove();
  }, [open]);

  async function send() {
    const content = text.trim();
    if (!content || busy) return;
    const next: Msg[] = [...msgs, { role: "user", content }];
    setMsgs(next);
    setText("");
    setError("");
    setBusy(true);
    const r = await authed<{ reply?: string; products?: Card[]; error?: string }>(null, "POST", "/api/tila", { locale: getLang(), messages: next.slice(-10).map(({ role, content }) => ({ role, content })) });
    setBusy(false);
    if (r.status === 0) setError(tr("Connexion impossible : vérifiez votre réseau et réessayez.", "Connection failed: check your network and try again."));
    else if (!r.ok || !r.data?.reply) setError(T.errors[r.data?.error ?? "unavailable"] ?? T.errors.unavailable);
    else setMsgs([...next, { role: "assistant", content: r.data.reply, products: r.data.products ?? [] }]);
  }

  return (
    <>
      <View pointerEvents="box-none" style={StyleSheet.absoluteFill} onLayout={(e) => setBox({ w: e.nativeEvent.layout.width, h: e.nativeEvent.layout.height })}>
        <Animated.View {...pan.panHandlers} onLayout={(e) => setSize({ w: e.nativeEvent.layout.width, h: e.nativeEvent.layout.height })} accessibilityRole="button" accessibilityLabel={T.open} style={[st.fab, { left: pos.x, top: pos.y }]}>
          <Image source={{ uri: AVATAR }} style={st.fabImg} />
          <View><Text style={st.fabName}>{T.name}</Text><Text style={st.fabBadge}>{T.badge}</Text></View>
        </Animated.View>
      </View>
      {open && (
        <View style={[StyleSheet.absoluteFill, { zIndex: 1000, elevation: 20, backgroundColor: "#faf6ee" }]}>
          <View style={{ flex: 1 }}>
            <KeyboardAvoidingView style={{ flex: 1 }} behavior={Platform.OS === "ios" ? "padding" : "padding"}>
              <View style={st.head}>
                <Image source={{ uri: AVATAR }} style={st.headImg} />
                <View style={{ flex: 1 }}><Text style={st.name}>{T.name}</Text><Text style={st.badge}>{T.badge}</Text></View>
                <Pressable onPress={() => setOpen(false)} hitSlop={10} accessibilityLabel={tr("Fermer", "Close")}><Text style={{ fontSize: 28, color: "#221812" }}>×</Text></Pressable>
              </View>
              <ScrollView ref={scroller} onContentSizeChange={() => scroller.current?.scrollToEnd()} contentContainerStyle={{ padding: 12, gap: 10 }} keyboardShouldPersistTaps="handled">
                <Text style={[st.bubble, { backgroundColor: "#f2eadd" }]}>{T.hello}</Text>
                {msgs.map((m, i) => (
                  <View key={i} style={{ alignItems: m.role === "user" ? "flex-end" : "flex-start", gap: 6 }}>
                    <Text style={[st.bubble, m.role === "user" ? { backgroundColor: "#1c3060", color: "#fff" } : { backgroundColor: "#f2eadd" }]}>{m.content}</Text>
                    {m.products?.map((p) => (
                      <Pressable key={p.slug} onPress={() => { setOpen(false); onOpenSlug(p.slug); }} style={st.card}>
                        {p.image ? <Image source={{ uri: abs(p.image) }} style={st.thumb} /> : null}
                        <View style={{ flex: 1 }}><Text style={{ fontWeight: "700", color: "#221812" }}>{p.name}</Text><Text style={{ fontSize: 12, color: "#6b5d52" }}>{p.creatorName}</Text></View>
                        <Text style={{ fontWeight: "700", color: "#221812" }}>{eur(p.priceCents)}</Text>
                      </Pressable>
                    ))}
                  </View>
                ))}
                {busy && <View style={{ flexDirection: "row", gap: 8 }}><ActivityIndicator /><Text style={{ color: "#6b5d52" }}>{T.thinking}</Text></View>}
                {!!error && <Text style={{ color: "#a33" }}>{error}</Text>}
              </ScrollView>
              <View style={st.form}>
                <TextInput value={text} onChangeText={setText} maxLength={500} placeholder={T.placeholder} placeholderTextColor="#6b5d52" selectionColor="#1c3060" onSubmitEditing={send} returnKeyType="send" style={st.input} />
                <Pressable onPress={send} disabled={busy || !text.trim()} style={[st.send, (busy || !text.trim()) && { opacity: 0.5 }]}><Text style={{ color: "#fff", fontWeight: "700" }}>{T.send}</Text></Pressable>
              </View>
              <Text style={st.notice}>{T.notice}</Text>
            </KeyboardAvoidingView>
          </View>
        </View>
      )}
    </>
  );
}

const st = StyleSheet.create({
  fab: { position: "absolute", zIndex: 900, flexDirection: "row", alignItems: "center", gap: 8, backgroundColor: "#1c3060", borderRadius: 40, paddingVertical: 4, paddingLeft: 4, paddingRight: 14, elevation: 6 },
  fabImg: { width: 44, height: 44, borderRadius: 22, borderWidth: 2, borderColor: "#f59e0b" },
  fabName: { color: "#fff", fontWeight: "600", fontSize: 14 },
  fabBadge: { color: "#fff", opacity: 0.8, fontSize: 11 },
  head: { flexDirection: "row", alignItems: "center", gap: 10, padding: 12, borderBottomWidth: 1, borderColor: "#ded6c9" },
  headImg: { width: 40, height: 40, borderRadius: 20, borderWidth: 2, borderColor: "#f59e0b" },
  name: { fontFamily: "PlayfairDisplay_600SemiBold", fontSize: 18, color: "#221812" },
  badge: { fontSize: 12, color: "#6b5d52" },
  bubble: { padding: 10, borderRadius: 10, maxWidth: "90%", color: "#221812", overflow: "hidden" },
  card: { flexDirection: "row", alignItems: "center", gap: 10, borderWidth: 1, borderColor: "#ded6c9", borderRadius: 8, padding: 8, backgroundColor: "#fff", alignSelf: "stretch" },
  thumb: { width: 56, height: 56, borderRadius: 4 },
  form: { flexDirection: "row", gap: 8, padding: 12, borderTopWidth: 1, borderColor: "#ded6c9" },
  input: { flex: 1, borderWidth: 1, borderColor: "#ded6c9", backgroundColor: "#fff", color: "#221812", paddingHorizontal: 12, paddingVertical: 8, fontSize: 16 },
  send: { backgroundColor: "#1c3060", paddingHorizontal: 16, justifyContent: "center", borderRadius: 4 },
  notice: { fontSize: 11, color: "#6b5d52", paddingHorizontal: 12, paddingBottom: 8 },
});
