"use client";

import Image from "next/image";
import Link from "next/link";
import { useEffect, useRef, useState } from "react";
import { formatEur, type Locale } from "@/lib/i18n";

type Card = { slug: string; name: string; creatorName: string; priceCents: number; image: string | null };
type Msg = { role: "user" | "assistant"; content: string; products?: Card[] };

const T = {
  fr: {
    name: "Tílá",
    badge: "Assistant IA",
    open: "Ouvrir Tílá, l'assistant IA d'achat",
    close: "Fermer",
    enlarge: "Agrandir la photo de Tílá",
    alt: "Tílá, assistant IA de E póm ta’",
    hello: "Bonjour, je suis Tílá, votre assistant IA. Dites-moi ce que vous cherchez (occasion, tissu, budget) et je vous montre des pièces en stock.",
    placeholder: "Votre message…",
    send: "Envoyer",
    notice: "Réponses générées par une IA, qui peut se tromper. Ne saisissez pas de données personnelles.",
    thinking: "Tílá réfléchit…",
    errors: { rate: "Vous avez posé beaucoup de questions : réessayez dans un moment.", unavailable: "Tílá est momentanément indisponible. Réessayez plus tard.", invalid: "Message trop long ou invalide." },
  },
  en: {
    name: "Tílá",
    badge: "AI assistant",
    open: "Open Tílá, the AI shopping assistant",
    close: "Close",
    enlarge: "Enlarge Tílá's photo",
    alt: "Tílá, AI assistant of E póm ta’",
    hello: "Hello, I'm Tílá, your AI assistant. Tell me what you are looking for (occasion, fabric, budget) and I'll show you pieces in stock.",
    placeholder: "Your message…",
    send: "Send",
    notice: "Answers are generated by an AI and may be wrong. Do not enter personal data.",
    thinking: "Tílá is thinking…",
    errors: { rate: "You have asked a lot of questions: please try again in a moment.", unavailable: "Tílá is temporarily unavailable. Please try again later.", invalid: "Message too long or invalid." },
  },
} as const;

export function TilaChat({ locale }: { locale: Locale }) {
  const t = T[locale === "en" ? "en" : "fr"];
  const [open, setOpen] = useState(false);
  const [msgs, setMsgs] = useState<Msg[]>([]);
  const [text, setText] = useState("");
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState("");
  const [zoom, setZoom] = useState(false);
  const endRef = useRef<HTMLDivElement>(null);
  const inputRef = useRef<HTMLInputElement>(null);
  const openerRef = useRef<HTMLButtonElement>(null);

  useEffect(() => {
    if (!open) return;
    inputRef.current?.focus();
    const onKey = (e: KeyboardEvent) => {
      if (e.key === "Escape") {
        if (zoom) return setZoom(false);
        setOpen(false);
        openerRef.current?.focus();
      }
    };
    document.addEventListener("keydown", onKey);
    return () => document.removeEventListener("keydown", onKey);
  }, [open, zoom]);

  useEffect(() => {
    endRef.current?.scrollIntoView({ block: "end" });
  }, [msgs, busy]);

  async function send(e: React.FormEvent) {
    e.preventDefault();
    const content = text.trim();
    if (!content || busy) return;
    const next: Msg[] = [...msgs, { role: "user", content }];
    setMsgs(next);
    setText("");
    setError("");
    setBusy(true);
    try {
      const res = await fetch("/api/tila", {
        method: "POST",
        headers: { "content-type": "application/json" },
        body: JSON.stringify({ locale, messages: next.slice(-10).map(({ role, content }) => ({ role, content })) }),
      });
      const data = (await res.json().catch(() => ({}))) as { reply?: string; products?: Card[]; error?: string };
      if (!res.ok || !data.reply) {
        setError(t.errors[(data.error as keyof typeof t.errors) ?? "unavailable"] ?? t.errors.unavailable);
      } else {
        setMsgs([...next, { role: "assistant", content: data.reply, products: data.products ?? [] }]);
      }
    } catch {
      setError(t.errors.unavailable);
    } finally {
      setBusy(false);
    }
  }

  const avatar = (size: number) => (
    <Image src="/tila-avatar.jpeg" alt="" width={size} height={size} className="rounded-full border-2 border-amber-500 object-cover" style={{ width: size, height: size }} />
  );

  return (
    <>
      {!open && (
        <button
          ref={openerRef}
          type="button"
          onClick={() => setOpen(true)}
          aria-label={t.open}
          className="fixed bottom-24 right-4 z-40 flex items-center gap-2 rounded-full bg-primary py-1 pl-1 pr-4 text-primary-foreground shadow-lg md:bottom-6"
        >
          <Image src="/tila-avatar.jpeg" alt={t.alt} width={48} height={48} className="rounded-full border-2 border-amber-500 object-cover" style={{ width: 48, height: 48 }} />
          <span className="text-sm font-medium leading-tight">
            {t.name}
            <span className="block text-[11px] font-normal opacity-80">{t.badge}</span>
          </span>
        </button>
      )}
      {open && (
        <section
          role="dialog"
          aria-label={`${t.name} — ${t.badge}`}
          className="fixed inset-x-2 bottom-2 z-50 flex max-h-[80vh] flex-col rounded-xl border bg-background shadow-2xl md:inset-x-auto md:bottom-6 md:right-4 md:w-96"
        >
          <header className="flex items-center gap-3 border-b p-3">
            <button type="button" onClick={() => setZoom(true)} aria-label={t.enlarge} className="rounded-full">
              {avatar(40)}
            </button>
            <div className="flex-1 leading-tight">
              <p className="font-semibold">{t.name}</p>
              <p className="text-xs text-muted-foreground">{t.badge}</p>
            </div>
            <button type="button" onClick={() => { setOpen(false); openerRef.current?.focus(); }} aria-label={t.close} className="rounded p-2 text-lg leading-none">
              ×
            </button>
          </header>
          <div className="flex-1 space-y-3 overflow-y-auto p-3 text-sm" aria-live="polite">
            <p className="rounded-lg bg-muted p-2">{t.hello}</p>
            {msgs.map((m, i) => (
              <div key={i} className={m.role === "user" ? "text-right" : ""}>
                <p className={`inline-block max-w-[90%] whitespace-pre-wrap rounded-lg p-2 text-left ${m.role === "user" ? "bg-primary text-primary-foreground" : "bg-muted"}`}>{m.content}</p>
                {m.products?.map((p) => (
                  <Link key={p.slug} href={`/${locale}/produits/${p.slug}`} className="mt-2 flex items-center gap-3 rounded-lg border p-2 text-left hover:bg-muted">
                    {p.image && (
                      // eslint-disable-next-line @next/next/no-img-element
                      <img src={p.image} alt="" width={56} height={56} className="h-14 w-14 rounded object-cover" />
                    )}
                    <span className="flex-1">
                      <span className="block font-medium">{p.name}</span>
                      <span className="block text-xs text-muted-foreground">{p.creatorName}</span>
                    </span>
                    <span className="font-semibold">{formatEur(p.priceCents, locale)}</span>
                  </Link>
                ))}
              </div>
            ))}
            {busy && <p className="text-muted-foreground">{t.thinking}</p>}
            {error && <p role="alert" className="text-red-700">{error}</p>}
            <div ref={endRef} />
          </div>
          <form onSubmit={send} className="flex gap-2 border-t p-3">
            <input ref={inputRef} value={text} onChange={(e) => setText(e.target.value)} maxLength={500} placeholder={t.placeholder} aria-label={t.placeholder} className="min-w-0 flex-1 rounded border px-3 py-2 text-base" />
            <button type="submit" disabled={busy || !text.trim()} className="rounded bg-primary px-4 py-2 text-primary-foreground disabled:opacity-50">
              {t.send}
            </button>
          </form>
          <p className="px-3 pb-2 text-[11px] text-muted-foreground">{t.notice}</p>
        </section>
      )}
      {open && zoom && (
        <div role="dialog" aria-modal="true" aria-label={t.alt} onClick={() => setZoom(false)} className="fixed inset-0 z-[60] flex items-center justify-center bg-black/80 p-4">
          <button type="button" autoFocus onClick={() => setZoom(false)} aria-label={t.close} className="absolute right-3 top-3 rounded bg-white/90 px-3 py-1 text-2xl leading-none text-black">
            ×
          </button>
          <div onClick={(e) => e.stopPropagation()} className="          aspect-square w-[min(85vw,85vh,32rem)] shrink-0 overflow-hidden rounded-full">
                      <Image src="/tila-avatar.jpeg" alt={t.alt} width={1208} height={1208} className="h-full w-full object-cover object-center" />
          </div>
        </div>
      )}
    </>
  );
}
