const dictionaries: Record<Locale, Dict> = { fr, en };

export function getDict(locale: Locale): Dict {
  return dictionaries[locale];
}

export type { Dict };

/** Choisit le champ FR ou EN d'un objet bilingue (`name` / `nameEn`). */
export function pick(locale: Locale, fr: string, en: string): string {
  return locale === "en" ? en : fr;
}

export function formatEur(cents: number, locale: Locale): string {
  return new Intl.NumberFormat(locale === "en" ? "en-GB" : "fr-FR", {
    style: "currency",
    currency: "EUR",
    maximumFractionDigits: cents % 100 === 0 ? 0 : 2,
  }).format(cents / 100);
}
